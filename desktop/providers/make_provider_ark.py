"""Regenerate providers/provider-ark/ from the published @hypit/provider-tokendance dist.

TokenDance speaks the same Ark task protocol as Volcengine Ark, behind its own gateway paths and model names.
This script copies the compiled package and rewrites only what differs, so a newer upstream can be re-applied:

    python providers/make_provider_ark.py <dir with the unpacked tokendance package> providers/provider-ark
"""
from __future__ import annotations

import json
import re
import shutil
import sys
from pathlib import Path

PACKAGE = "@hypit-desktop/provider-ark"
BASE_URL = "https://ark.cn-beijing.volces.com/api/v3"
PRICING_URL = "https://www.volcengine.com/docs/82379/1544106"
# Capability -> Ark model id (the id shown in the Ark console for the model the account enabled), shared with the app.
MODELS = json.loads((Path(__file__).with_name("ark_models.json")).read_text(encoding="utf-8"))
UPSTREAM_SEEDANCE = {"seedance-2": "seedance-2.0", "seedance-2-fast": "seedance-2.0-fast",
                     "seedance-2-mini": "seedance-2.0-mini", "seedance-2.5": "seedance-2.5"}


def replace(text: str, old: str, new: str, count: int = 1) -> str:
    if text.count(old) < 1:
        raise SystemExit(f"expected text not found: {old[:70]!r}")
    return text.replace(old, new) if count == 0 else text.replace(old, new, count)


def rename(text: str) -> str:
    text = text.replace("@hypit/provider-tokendance", PACKAGE).replace("hypit.tokendance-operation@1", "hypit.ark-operation@1")
    text = text.replace("TOKENDANCE_", "ARK_").replace("TokenDance", "Ark").replace("tokenDance", "ark")
    text = text.replace("tokendance.default", "ark.default").replace("tokendance.api-key", "ark.api-key")
    return text


def main(source: Path, target: Path) -> None:
    if target.exists():
        shutil.rmtree(target)
    (target / "dist").mkdir(parents=True)
    for name in ("activation.js", "errors.js", "index.js", "mapping.js", "provider.js", "routes.js"):
        (target / "dist" / name).write_text(rename((source / "dist" / name).read_text(encoding="utf-8")), encoding="utf-8")

    provider = target / "dist" / "provider.js"
    text = provider.read_text(encoding="utf-8")
    text = replace(text, '"https://tokendance.space/gateway"', f'"{BASE_URL}"')
    text = replace(text, "/ark/v3/generations/tasks", "/contents/generations/tasks", 0)
    text = replace(text, "/ark/v3/images/generations", "/images/generations")
    text = re.sub(r'pricing: \{ kind: "page", url: "[^"]+" \}', f'pricing: {{ kind: "page", url: "{PRICING_URL}" }}', text)
    provider.write_text(text, encoding="utf-8")

    mapping = target / "dist" / "mapping.js"
    text = mapping.read_text(encoding="utf-8")
    for capability, wire in UPSTREAM_SEEDANCE.items():
        text = replace(text, f'seedance("{capability}", "{wire}")', f'seedance("{capability}", "{MODELS[capability]}")')
    text = replace(text, 'routes: [{ model: "seedream-5.0-lite" }]', f'routes: [{{ model: "{MODELS["seedream-5-lite"]}" }}]')
    text = re.sub(r'\n    \{\n        capability: \{ module: MINIMAX.*?\n    \},\n', "\n", text, flags=re.S)
    mapping.write_text(text, encoding="utf-8")

    routes = target / "dist" / "routes.js"
    text = routes.read_text(encoding="utf-8")
    text = replace(text, "        output_format: input.output_format,\n", "")  # the flash model documents no output_format field
    routes.write_text(text, encoding="utf-8")

    manifest = json.loads((source / "package.json").read_text(encoding="utf-8"))
    manifest.update(name=PACKAGE, version="0.1.0", description="Volcengine Ark (Doubao Seedance / Seedream) Provider for Hypit, derived from @hypit/provider-tokendance")
    manifest.pop("repository", None)
    manifest["files"] = ["dist", "README.md", "LICENSE"]
    (target / "package.json").write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    shutil.copy2(source / "LICENSE", target / "LICENSE")
    (target / "README.md").write_text(
        "# provider-ark\n\nDerived from `@hypit/provider-tokendance` (Hypit license: internal use). Generated by "
        "`providers/make_provider_ark.py`; do not edit `dist` by hand.\n\n"
        "Capabilities: `@hypit/seedance@1#seedance-2-mini` and `@hypit/seedream@1#seedream-5-lite` "
        "(served by the Ark Seedream 5.0 flash model).\n", encoding="utf-8")


if __name__ == "__main__":
    main(Path(sys.argv[1]), Path(sys.argv[2]))
